//operador and
let edades:number=23
let licencia:boolean=true

console.log(edades>=18 && licencia==true);//Ambas tienen que ser verdaderas para ser TRUE

//operador OR
console.log(edades>=18 || licencia==true);//Alguna condicion tiene que ser verdadera para ser TRUE

//operador NOT
console.log(!licencia);//SImbolo ! niega el resultado
